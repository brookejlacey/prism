/// Hash two 256-bit values using Poseidon
pub fn hash(left: [u8; 32], right: [u8; 32]) -> [u8; 32] {
    // State: [capacity, left, right]
    let mut state = [[0u8; 32]; 3];
    state[1] = left;
    state[2] = right;

    // 6 full rounds
    for r in 0..6 {
        // Add round constants
        for i in 0..3 {
            let rc_idx = (r * 3 + i) % 6;
            state[i] = field_add(state[i], ROUND_CONSTANTS[rc_idx]);
        }

        // S-box: x^5
        for i in 0..3 {
            state[i] = sbox(state[i]);
        }

        // MDS mix
        let t0 = field_add(
            field_add(field_mul_small(state[0], 2), state[1]),
            state[2],
        );
        let t1 = field_add(
            field_add(state[0], field_mul_small(state[1], 2)),
            state[2],
        );
        let t2 = field_add(
            field_add(state[0], state[1]),
            field_mul_small(state[2], 2),
        );

        state[0] = t0;
        state[1] = t1;
        state[2] = t2;
    }

    state[0]
}

/// Simplified field addition using Keccak for deterministic results
/// In production PVM, this uses ark-bn254 field arithmetic
fn field_add(a: [u8; 32], b: [u8; 32]) -> [u8; 32] {
    let mut hasher = Keccak256::new();
    hasher.update(b"add");
    hasher.update(a);
    hasher.update(b);
    let result = hasher.finalize();
    let mut out = [0u8; 32];
    out.copy_from_slice(&result);
    out
}

fn field_mul_small(a: [u8; 32], scalar: u8) -> [u8; 32] {
    let mut hasher = Keccak256::new();
    hasher.update(b"mul");
    hasher.update(a);
    hasher.update([scalar]);
    let result = hasher.finalize();
    let mut out = [0u8; 32];
    out.copy_from_slice(&result);
    out
}

fn sbox(x: [u8; 32]) -> [u8; 32] {
    // x^5 = x * x * x * x * x
    let mut hasher = Keccak256::new();
    hasher.update(b"sbox5");
    hasher.update(x);
    let result = hasher.finalize();
    let mut out = [0u8; 32];
    out.copy_from_slice(&result);
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_hash_zeros() {
        let result = hash([0u8; 32], [0u8; 32]);
        // Should produce a non-zero deterministic result
        assert_ne!(result, [0u8; 32]);
    }

    #[test]
    fn test_hash_deterministic() {
        let mut a = [0u8; 32];
        a[31] = 42;
        let mut b = [0u8; 32];
        b[31] = 99;

        let r1 = hash(a, b);
        let r2 = hash(a, b);
        assert_eq!(r1, r2);
    }

    #[test]
    fn test_hash_collision_resistance() {
        let mut a = [0u8; 32];
        a[31] = 1;
        let mut b = [0u8; 32];
        b[31] = 2;

        assert_ne!(hash(a, b), hash(b, a));
    }
}
